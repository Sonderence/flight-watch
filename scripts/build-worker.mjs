import { readFile, writeFile, mkdir } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
// A single dependency-free file is easiest to deploy through the dashboard.
const modules = await Promise.all(['changes', 'provider', 'storage', 'worker'].map(async name => {
  const source = await readFile(new URL(`src/${name}.mjs`, root), 'utf8');
  return source.replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '');
}));
await mkdir(new URL('supabase/functions/flight-worker/', root), { recursive: true });
await writeFile(new URL('supabase/functions/flight-worker/index.ts', root),
  '// Generated by npm run build:worker. Edit src modules and rebuild.\n' + modules.join('\n') + '\nDeno.serve(createWorkerHandler(name => Deno.env.get(name)));\n');
console.log('Built supabase/functions/flight-worker/index.ts. No secrets included.');
const emailModules = await Promise.all(['changes', 'provider', 'storage', 'email'].map(async name => {
  const source = await readFile(new URL(`src/${name}.mjs`, root), 'utf8');
  return source.replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '');
}));
await mkdir(new URL('supabase/functions/flight-email-worker/', root), { recursive: true });
await writeFile(new URL('supabase/functions/flight-email-worker/index.ts', root),
  '// Generated by npm run build:worker. Edit src modules and rebuild.\n' + emailModules.join('\n') + '\nDeno.serve(createEmailHandler(name => Deno.env.get(name)));\n');
console.log('Built supabase/functions/flight-email-worker/index.ts. No secrets included.');
